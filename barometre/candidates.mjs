export const normalizeName = value => String(value||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
export function mergeCandidates(rows){
 const used=new Set();
 const merged=snapshot.map((candidate,index)=>{
  const found=rows.find(r=>normalizeName(r.full_name)===normalizeName(candidate.full_name));
  if(found)used.add(found.id);
  return {...candidate,...(found||{}),full_name:candidate.full_name,political_group:candidate.political_group,photo_url:candidate.photo_url,id:found?.id||'pending-'+index,voting_available:!!found};
 });
 return merged.concat(rows.filter(r=>!used.has(r.id)).map(r=>({...r,voting_available:true})));
}
